def document_messages(document: LegalDocument, max_length: int = 3800) -> list[str]:
    """Разбивает документ по разделам, соблюдая лимит Telegram-сообщения."""
    header = f"<b>{escape(document.title)} — {PROJECT_NAME}</b>\nРедакция: {DOCUMENT_DATE}\n\n"
    messages = []
    current = header
    for heading, text in document.sections:
        section = f"<b>{escape(heading)}</b>\n{escape(text)}\n\n"
        if len(current) + len(section) > max_length:
            messages.append(current.rstrip())
            current = header + section
        else:
            current += section
    if current.strip():
        messages.append(current.rstrip())
    return messages


def public_tariff_rows(tariffs, settings) -> list[dict]:
    """Цены и ограничения из действующих настроек, без выдуманных тарифов."""
    from tgbot.services.device_pricing import slots_cost_for_tariff

    return [{
        "name": tariff.name,
        "price": f"{tariff.price:.2f}",
        "duration_days": tariff.duration_days,
        "base_limit": settings.base_limit,
        "quota": f"{tariff.data_limit_gb} ГБ в месяц" if tariff.data_limit_gb else "Без лимита объема",
        "loyalty_price": f"{tariff.loyalty_price:.2f}" if tariff.loyalty_price else None,
        "price_stars": getattr(tariff, "price_stars", None),
        "extra_price": f"{slots_cost_for_tariff(settings, tariff.duration_days, 1):.2f}",
        "max_extra": settings.max_extra,
    } for tariff in tariffs]
