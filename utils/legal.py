def platega_review_mode() -> bool:
    return os.getenv("PLATEGA_REVIEW_MODE", "true").strip().lower() not in {
        "0", "false", "no", "off",
    }


def telegram_support_url(username: str | None) -> str | None:
    value = (username or "").strip().lstrip("@")
    if not re.fullmatch(r"[A-Za-z0-9_]{5,32}", value):
        return None
    return f"https://t.me/{value}?start=support"


